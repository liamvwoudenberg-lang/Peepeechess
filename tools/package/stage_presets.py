#!/usr/bin/env python3
"""Compose the export_presets.cfg of the staging project used by build_pc.sh.

Windows : the repository's own godot/export_presets.cfg "Windows Desktop" preset (the project's canonical
          release configuration) when present; otherwise the fallback preset in tools/package/export_presets.cfg.
          Only packaging-related fields are adjusted: product name for TARGET=arena and the include_filter, which
          must contain *.json and *.wav so runtime-read data files are packed (a missing entry is added, never removed).
Linux   : tools/package/export_presets.cfg (the repository has no Linux preset).

usage: stage_presets.py REPO_CFG TOOLS_CFG OUT_CFG TITLE [auto|repo|tools] [extra include glob ...]
Prints one line naming the source of the Windows preset.
"""
import re
import sys


def sections(text):
    out, cur = [], None
    for line in text.splitlines():
        m = re.match(r"^\[(.+)\]\s*$", line)
        if m:
            cur = [m.group(1), []]
            out.append(cur)
        elif cur is not None:
            cur[1].append(line)
    return out


def find_preset(text, name):
    """Return (settings lines, option lines) of the preset called `name`, or None."""
    secs = sections(text)
    for title, body in secs:
        if re.fullmatch(r"preset\.\d+", title) and any(re.fullmatch(rf'name="{re.escape(name)}"', l.strip()) for l in body):
            opts = next((b for t, b in secs if t == title + ".options"), [])
            return list(body), list(opts)
    return None


def set_key(lines, key, value):
    pat = re.compile(rf"^{re.escape(key)}=")
    for i, l in enumerate(lines):
        if pat.match(l):
            lines[i] = f"{key}={value}"
            return
    lines.append(f"{key}={value}")


def get_key(lines, key):
    for l in lines:
        if l.startswith(key + "="):
            return l.split("=", 1)[1].strip().strip('"')
    return ""


def emit(index, preset):
    body, opts = preset
    while body and not body[-1].strip():
        body.pop()
    while opts and not opts[-1].strip():
        opts.pop()
    return f"[preset.{index}]\n\n" + "\n".join(body).strip("\n") + f"\n\n[preset.{index}.options]\n\n" + "\n".join(opts).strip("\n") + "\n"


def main():
    repo_cfg, tools_cfg, out_cfg, title = sys.argv[1:5]
    source = sys.argv[5] if len(sys.argv) > 5 else "auto"
    extra = sys.argv[6:]
    tools = open(tools_cfg, encoding="utf-8").read()
    try:
        repo = open(repo_cfg, encoding="utf-8").read()
    except FileNotFoundError:
        repo = ""
    win, used = None, "tools"
    if source in ("auto", "repo"):
        win = find_preset(repo, "Windows Desktop")
        used = "repo"
        if win is None and source == "repo":
            sys.exit("godot/export_presets.cfg has no 'Windows Desktop' preset")
    if win is None:
        win, used = find_preset(tools, "Windows Desktop"), "tools"
    lin = find_preset(tools, "Linux")
    if win is None or lin is None:
        sys.exit("missing Windows Desktop or Linux preset")
    for preset in (win, lin):
        body, opts = preset
        flt = [f for f in get_key(body, "include_filter").split(",") if f]
        for needed in ["*.json", "*.wav", *extra]:
            if needed not in flt:
                flt.append(needed)
        set_key(body, "include_filter", '"' + ",".join(flt) + '"')
        set_key(body, "export_path", '""')
        set_key(opts, "application/product_name", f'"{title}"') if any(l.startswith("application/product_name=") for l in opts) else None
    # The staged presets are used with --export-release and an explicit output path.
    open(out_cfg, "w", encoding="utf-8").write(
        "; Generated by tools/package/stage_presets.py - staging copy only, never committed.\n\n" + emit(0, win) + "\n" + emit(1, lin))
    print(used)


main()
